"""Deriving a loan's postings from what was asserted about it.

A proposal, proved read-only. Nothing here writes, and nothing in the running
application calls it yet — ``tools/replay_loans.py`` uses it to replay every
loan in a journal and diff the result against what is stored.

WHY
---
``ledger`` today holds two different kinds of row in one table. A ``Repayment``
that payroll actually took is a *fact*. The ``Interest Earned`` row beside it
was generated by the application from the loan's terms — a *consequence*.
Nothing marks which is which, so any recomputation has to guess what it may
regenerate and what it would be destroying. Every awkward part of the current
design follows from that:

* ``rebuild_loan_schedule`` deletes *all* repayments and interest, because it
  cannot tell asserted rows from derived ones;
* ``is_edited`` smuggles a payment amount through that deletion, so a manual
  edit survives a replay — which is why migration 004 had to drop its
  ``CHECK (is_edited IN (0,1))``;
* "which terms applied to the months a deleted suspension skipped?" has no
  answer, because ``loans.installment`` is a single current value with no
  history. That question is not hard; it is unanswerable *as currently stored*.

THE SHAPE
---------
Separate the two. :class:`LoanEvent` is the asserted list — disbursements,
term changes, suspensions, payments actually received. :func:`derive` is a pure
function from that list to every posting the loan implies. The ``ledger`` and
``loans`` tables become a projection of it, rebuildable exactly the way the
general ledger already is (migrations 005 and 010).

Terms carry an effective date, which is the piece that is missing today. With
it, "what was the installment in March 2025" is a lookup rather than a
heuristic, and deleting a past suspension re-derives those months under the
terms that were actually in force.

FIDELITY
--------
The month loop below mirrors ``LoanService.catch_up_loan`` deliberately —
accrue ``min(monthly_interest, unearned)``, then settle interest before
principal — so a replay can be diffed against real data. Any divergence is a
finding, not a modelling choice.
"""
from dataclasses import dataclass, field, replace
from datetime import datetime

from dateutil.relativedelta import relativedelta

# Event kinds. Everything a person or payroll asserts about a loan.
DISBURSED = "Disbursed"
TOPPED_UP = "ToppedUp"
TERMS_CHANGED = "TermsChanged"
SUSPENDED = "Suspended"
PAYMENT_RECEIVED = "PaymentReceived"
SETTLED = "Settled"

_MONEY = 2


def _d(value):
    """Parse a YYYY-MM-DD date, tolerating a timestamp suffix."""
    return datetime.strptime(str(value)[:10], "%Y-%m-%d")


def _iso(value):
    return value.strftime("%Y-%m-%d")


@dataclass(frozen=True)
class LoanEvent:
    """One asserted fact, effective on a date.

    ``seq`` orders events that share a date — a top-up and the payment that
    follows it in the same month are not interchangeable.
    """
    date: str
    kind: str
    seq: int = 0
    amount: float = 0.0
    installment: float = None
    monthly_interest: float = None
    unearned_interest: float = None
    until: str = None
    principal: float = None
    interest: float = None
    ref: object = None            # provenance: the row this came from

    def sort_key(self):
        return (self.date, self.seq)


@dataclass
class Terms:
    """The schedule in force at a point in time."""
    installment: float = 0.0
    monthly_interest: float = 0.0


@dataclass
class Posting:
    """One row the loan implies. The projection writes these."""
    date: str
    kind: str                     # 'Interest Earned' | 'Repayment'
    added: float = 0.0
    deducted: float = 0.0
    principal_portion: float = 0.0
    interest_portion: float = 0.0
    principal_balance: float = 0.0
    interest_balance: float = 0.0
    source_ref: object = None     # the event it came from, when asserted


@dataclass
class DerivedLoan:
    """Everything replaying a loan's events produces."""
    postings: list = field(default_factory=list)
    principal_balance: float = 0.0
    interest_balance: float = 0.0
    unearned_interest: float = 0.0
    next_due_date: str = None
    terms_timeline: list = field(default_factory=list)   # [(date, Terms)]
    suspension_windows: list = field(default_factory=list)
    settled: bool = False
    notes: list = field(default_factory=list)

    @property
    def total_repaid(self):
        return round(sum(p.deducted for p in self.postings), _MONEY)

    @property
    def total_accrued(self):
        return round(sum(p.added for p in self.postings
                         if p.kind == "Interest Earned"), _MONEY)


def terms_on(timeline, date):
    """The terms in force on ``date``.

    The lookup that today's schema cannot answer. With a dated timeline it is
    a scan, not a guess — and it is what makes re-deriving the months a deleted
    suspension skipped unambiguous.
    """
    current = Terms()
    for effective, terms in timeline:
        if effective <= date:
            current = terms
        else:
            break
    return current


# Events that change the loan's *state* take effect at the start of their date,
# so the month due that day is derived under the new state. A payment is a
# transaction within that month and lands after its accrual. Getting this
# backwards means a suspension starting on a due date still charges interest
# for the month it was meant to skip.
_STATE_EVENTS = (DISBURSED, TOPPED_UP, TERMS_CHANGED, SUSPENDED)


def _day_before(date):
    return _iso(_d(date) - relativedelta(days=1))


def _in_suspension(date, windows):
    return any(start <= date and (end is None or date < end) for start, end in windows)


def derive(events, up_to=None):
    """Replay asserted events into every posting they imply.

    Pure: no database, no clock, no configuration. Given the same events it
    returns the same postings, which is what makes it testable against real
    data and safe to re-run.

    Payments are *inputs*, not outputs. The application generates a repayment
    each due month today; here the amount actually received is asserted and the
    derivation decides only how it splits and what it leaves outstanding. That
    is the change that removes ``is_edited``: a manual amount is an assertion
    like any other, not an edit to a generated row that a replay must dodge.

    ``up_to`` bounds scheduled accrual, so a replay can be run as at a past
    date. Asserted events after it are ignored.
    """
    ordered = sorted(events, key=lambda e: e.sort_key())
    out = DerivedLoan()
    if not ordered:
        out.notes.append("no events")
        return out

    terms = Terms()
    principal = 0.0
    interest_bal = 0.0
    unearned = 0.0
    next_due = None
    # With no horizon given, derive up to the last asserted event: a replay
    # of what happened, not a projection of what is due next.
    limit = up_to or ordered[-1].date

    def record_terms(date):
        out.terms_timeline.append((date, replace(terms)))

    def accrue_until(horizon):
        """Advance through every due month up to ``horizon``, accruing interest.

        A suspended month advances the due date without accruing, which is what
        extends the term rather than forgiving the interest.
        """
        nonlocal next_due, unearned, interest_bal
        if next_due is None:
            return
        while next_due <= horizon:
            if _in_suspension(next_due, out.suspension_windows):
                next_due = _iso(_d(next_due) + relativedelta(months=1))
                continue
            accrual = round(min(terms.monthly_interest, unearned), _MONEY)
            if accrual > 0:
                unearned = round(unearned - accrual, _MONEY)
                interest_bal = round(interest_bal + accrual, _MONEY)
                out.postings.append(Posting(
                    date=next_due, kind="Interest Earned", added=accrual,
                    principal_balance=round(principal, _MONEY),
                    interest_balance=interest_bal))
            next_due = _iso(_d(next_due) + relativedelta(months=1))

    for event in ordered:
        if event.date > limit:
            break

        # Bring the loan up to the event, so it lands on the state the loan was
        # actually in. State changes apply before their own month accrues;
        # payments apply after it.
        horizon = _day_before(event.date) if event.kind in _STATE_EVENTS else event.date
        accrue_until(min(horizon, limit))

        if event.kind == DISBURSED:
            principal = round(principal + (event.amount or 0), _MONEY)
            unearned = round(unearned + (event.unearned_interest or 0), _MONEY)
            terms = Terms(installment=event.installment or terms.installment,
                          monthly_interest=(event.monthly_interest
                                            if event.monthly_interest is not None
                                            else terms.monthly_interest))
            record_terms(event.date)
            next_due = next_due or _iso(_d(event.date) + relativedelta(months=1))

        elif event.kind == TOPPED_UP:
            principal = round(principal + (event.amount or 0), _MONEY)
            unearned = round(unearned + (event.unearned_interest or 0), _MONEY)
            if event.installment is not None or event.monthly_interest is not None:
                terms = Terms(
                    installment=(event.installment if event.installment is not None
                                 else terms.installment),
                    monthly_interest=(event.monthly_interest
                                      if event.monthly_interest is not None
                                      else terms.monthly_interest))
                record_terms(event.date)

        elif event.kind == TERMS_CHANGED:
            terms = Terms(
                installment=(event.installment if event.installment is not None
                             else terms.installment),
                monthly_interest=(event.monthly_interest
                                  if event.monthly_interest is not None
                                  else terms.monthly_interest))
            record_terms(event.date)

        elif event.kind == SUSPENDED:
            out.suspension_windows.append((event.date, event.until))

        elif event.kind in (PAYMENT_RECEIVED, SETTLED):
            paid = round(event.amount or 0, _MONEY)
            # An asserted split wins; otherwise interest is settled first, which
            # is what catch_up_loan does.
            if event.interest is not None or event.principal is not None:
                interest_pay = round(event.interest or 0, _MONEY)
                principal_pay = round(event.principal or 0, _MONEY)
            else:
                interest_pay = round(min(paid, max(interest_bal, 0.0)), _MONEY)
                principal_pay = round(min(paid - interest_pay, max(principal, 0.0)), _MONEY)
            principal = round(principal - principal_pay, _MONEY)
            interest_bal = round(interest_bal - interest_pay, _MONEY)
            out.postings.append(Posting(
                date=event.date, kind="Repayment", deducted=paid,
                principal_portion=principal_pay, interest_portion=interest_pay,
                principal_balance=round(principal, _MONEY),
                interest_balance=interest_bal, source_ref=event.ref))
            if event.kind == SETTLED:
                out.settled = True

    # Everything after the last event, up to the horizon. Without this a loan
    # with no activity since disbursement never accrues at all.
    accrue_until(limit)

    out.principal_balance = round(principal, _MONEY)
    out.interest_balance = round(interest_bal, _MONEY)
    out.unearned_interest = round(unearned, _MONEY)
    out.next_due_date = next_due
    return out
